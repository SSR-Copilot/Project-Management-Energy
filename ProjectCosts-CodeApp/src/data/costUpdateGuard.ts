/**
 * The upsert guard of a PLAN of updates (dvopt T-01, CB-01): Land Lease and OPEX.
 *
 * With `@microsoft/power-apps` 1.3.1 an update is sent as `PATCH` with no `If-Match`, which Dataverse treats as an UPSERT: updating a row
 * another user has deleted CREATES a new row holding only the patched columns (no project, no business unit), which no screen shows.
 * Contracts guards every update with `updateRecordIfExists` (one GET per row, D120 §3). A Land Lease Period-1 save of 40 WTGs rewrites
 * 40 allocations, so a GET per row would add 40 requests; this reads the ids of one table in CHUNKS (key only, 40 ids per request, a
 * few in flight), so the usual save pays one extra request per table.
 *
 * `assertRowsExist` throws `RecordGoneError` for the first missing id, and the caller sends NOTHING. A failed read is a `DataError`, never
 * "gone". A delete landing between this read and the PATCH is the narrow race that stays (as for Contracts).
 */
import { getClient } from "@microsoft/power-apps/data";
// Generated by `pac code add-data-source`; the same import `client.ts` uses.
import { dataSourcesInfo } from "../../.power/schemas/appschemas/dataSourcesInfo";
import { DataError, RecordGoneError } from "@/platform/errors";
import { loggedCall } from "@/platform/requestLog";
import { guardedCall, primaryKeyOf, type GuardedUpdateClient } from "./client";
import { forEachLimit } from "./concurrency";
import { chunk, guid, idIn } from "./odata";

/** Existence reads in flight at once (one per 40 ids). */
export const EXISTENCE_READ_CONCURRENCY = 4;

type ReadClient = Pick<GuardedUpdateClient, "retrieveMultipleRecordsAsync">;

/**
 * Refuses (`RecordGoneError`, first missing id) unless every id exists in `entitySet`. Duplicates (any case) are read once; an empty list
 * reads nothing. `client` is injectable for tests.
 */
export async function assertRowsExist(
  operation: string,
  entitySet: string,
  ids: readonly string[],
  client: () => ReadClient = () => getClient(dataSourcesInfo) as unknown as ReadClient,
): Promise<void> {
  const unique: string[] = [];
  const seen = new Set<string>();
  for (const raw of ids) {
    let id: string;
    try {
      id = guid(raw);
    } catch (error) {
      throw new DataError(operation, error);
    }
    if (seen.has(id.toLowerCase())) continue;
    seen.add(id.toLowerCase());
    unique.push(id);
  }
  if (unique.length === 0) return;
  const primaryKey = primaryKeyOf(entitySet);
  if (!primaryKey) {
    throw new DataError(operation, `no primary key is known for ${entitySet}; refusing an unguarded update`);
  }

  const present = new Set<string>();
  await forEachLimit(chunk(unique), async (batch) => {
    const filter = idIn(primaryKey, batch);
    const rows = await loggedCall(
      "read", `${operation} (existence check)`,
      () => guardedCall(`${operation} (existence check)`, () =>
        client().retrieveMultipleRecordsAsync<Record<string, unknown>>(entitySet, {
          select: [primaryKey], ...(filter ? { filter } : {}), maxPageSize: batch.length,
        })),
      (found) => found.length,
    );
    for (const row of rows) {
      const id = row[primaryKey];
      if (typeof id === "string") present.add(id.toLowerCase());
    }
  }, EXISTENCE_READ_CONCURRENCY);

  const missing = unique.find((id) => !present.has(id.toLowerCase()));
  if (missing !== undefined) throw new RecordGoneError(operation, entitySet, missing);
}

/** Does the row exist? A failed read throws (it is never read as "absent"). */
export async function rowExists(
  operation: string,
  entitySet: string,
  id: string,
  client?: () => ReadClient,
): Promise<boolean> {
  try {
    await assertRowsExist(operation, entitySet, [id], client);
    return true;
  } catch (error) {
    if (error instanceof RecordGoneError) return false;
    throw error;
  }
}
